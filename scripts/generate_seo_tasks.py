from pathlib import Path
from html.parser import HTMLParser
from datetime import datetime, timezone
import re

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "SEO-TASK-BACKLOG.md"
BASE_URL = "https://3d-print-cost-calculator-7ce.pages.dev/"

class Inspector(HTMLParser):
    def __init__(self):
        super().__init__()
        self.title = []
        self.in_title = False
        self.description = ""
        self.h1 = []
        self.in_h1 = False
        self.h1_buf = []
        self.links = []
        self.text_parts = []
        self.in_script_style = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "title":
            self.in_title = True
        elif tag == "meta" and attrs.get("name", "").lower() == "description":
            self.description = attrs.get("content", "").strip()
        elif tag == "h1":
            self.in_h1 = True
            self.h1_buf = []
        elif tag == "a" and attrs.get("href"):
            self.links.append((attrs["href"].strip(), attrs.get("aria-label", "").strip()))
        elif tag in ("script", "style"):
            self.in_script_style += 1

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        elif tag == "h1" and self.in_h1:
            self.h1.append(" ".join("".join(self.h1_buf).split()))
            self.in_h1 = False
        elif tag in ("script", "style") and self.in_script_style:
            self.in_script_style -= 1

    def handle_data(self, data):
        if self.in_title:
            self.title.append(data)
        if self.in_h1:
            self.h1_buf.append(data)
        if not self.in_script_style:
            cleaned = " ".join(data.split())
            if cleaned:
                self.text_parts.append(cleaned)

def main():
    index = ROOT / "index.html"
    tasks = []
    notes = []
    if not index.exists():
        tasks.append(("P0", "公開対象ファイルの確認", "`index.html` がリポジトリ直下に見つかりません。現在のビルド構成と公開ディレクトリを確認してください。", "手動確認"))
        html = ""
        inspector = Inspector()
    else:
        html = index.read_text(encoding="utf-8", errors="replace")
        inspector = Inspector()
        inspector.feed(html)

        title = " ".join("".join(inspector.title).split())
        if not title:
            tasks.append(("P1", "ページタイトルを設定", "トップページに、サービス内容が伝わる固有の `<title>` を設定してください。", "静的HTML検査"))
        elif len(title) < 15 or len(title) > 60:
            tasks.append(("P2", "ページタイトルを見直す", f"現在のタイトルは `{title}` です。検索結果で内容が伝わる長さと表現か確認してください。", "静的HTML検査"))
        else:
            notes.append(f"ページタイトルを検出: `{title}`")

        if not inspector.description:
            tasks.append(("P1", "メタディスクリプションを追加", "検索結果でページ内容と利用メリットが伝わる `<meta name=\"description\">` を追加してください。", "静的HTML検査"))
        elif len(inspector.description) < 50 or len(inspector.description) > 180:
            tasks.append(("P2", "メタディスクリプションを確認", f"説明文は {len(inspector.description)} 文字です。検索ユーザーにとって具体的で自然な文章か見直してください。", "静的HTML検査"))

        if not inspector.h1:
            tasks.append(("P1", "主見出し（H1）を追加", "トップページの主題を示すH1を1つ設け、原価計算ツールの用途を明確にしてください。", "静的HTML検査"))
        elif len(inspector.h1) > 1:
            tasks.append(("P2", "見出し階層を確認", f"H1が {len(inspector.h1)} 個検出されました。ページ構造として適切か確認してください。", "静的HTML検査"))

        text = " ".join(inspector.text_parts).lower()
        topic_groups = [
            (("原価", "cost"), "原価計算の説明を具体化", "材料費・電気代・造形時間など、実際に計算できる項目を正確に説明するセクションを検討してください。"),
            (("フィラメント", "filament"), "フィラメント費用の案内を追加", "フィラメント使用量や単価から材料費を求める方法を、計算ツールへの導線付きで説明するページ案を作成してください。"),
            (("販売価格", "利益率", "profit"), "販売価格・利益率のガイドを追加", "原価から販売価格や利益を考えるための独自性あるガイドを作成し、ツールへ内部リンクしてください。"),
            (("使い方", "faq", "よくある質問"), "使い方・FAQを改善", "初めての利用者が入力項目と計算結果を理解できるよう、具体例付きのFAQ案を作成してください。"),
        ]
        for needles, title_text, body in topic_groups:
            if not any(n in text for n in needles):
                tasks.append(("P2", title_text, body, "コンテンツ確認が必要"))

        if not any("sitemap" in p.name.lower() for p in ROOT.iterdir() if p.is_file()):
            tasks.append(("P2", "サイトマップの配置を確認", "公開先に `sitemap.xml` が含まれ、実際の公開URLと一致しているか確認してください。", "ファイル確認"))

        # Keep a durable recurring backlog; this script proposes tasks only and does not edit site content.
        if not tasks:
            tasks.append(("P3", "検索データを見て改善候補を選ぶ", "Google Search Consoleの検索クエリ・表示回数・クリック率を確認し、実データに基づく改善を選定してください。", "Search Consoleで手動確認"))

    priority_rank = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}
    tasks.sort(key=lambda x: priority_rank.get(x[0], 9))
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# SEO Improvement Task Backlog",
        "",
        f"- Updated: {now}",
        f"- Site: {BASE_URL}",
        "- Generated by: `scripts/generate_seo_tasks.py`",
        "- Mode: suggestions only; this script does not publish or modify site content.",
        "",
        "## Priority guide",
        "- **P0**: build/publication blocker requiring immediate investigation",
        "- **P1**: important page-level SEO or usability issue",
        "- **P2**: useful content or technical improvement",
        "- **P3**: improvement requiring external analytics or human judgment",
        "",
        "## Suggested tasks",
        "",
    ]
    for i, (priority, title, body, evidence) in enumerate(tasks, 1):
        lines.extend([
            f"### {i}. [{priority}] {title}",
            "",
            body,
            "",
            f"- Basis: {evidence}",
            "- Completion check: inspect the page and run the site check again.",
            "",
        ])
    lines.extend([
        "## Observations",
        "",
    ])
    lines.extend([f"- {note}" for note in notes] or ["- No additional observations recorded."])
    lines.extend([
        "",
        "## Important limitations",
        "",
        "- This report is based on the repository's static `index.html`; it does not crawl the live site.",
        "- It does not connect to Google Search Console and cannot infer rankings, traffic, or conversion.",
        "- Tasks are suggestions, not proof of SEO defects. Review before editing or publishing.",
        "- Avoid mass-generated thin or duplicate pages; prioritize useful, accurate content.",
        "",
    ])
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {REPORT.name} with {len(tasks)} task(s).")

if __name__ == "__main__":
    main()
